"""One-command build.

    python build/build.py            build dist/DesktopOrganizer.exe (Windows) and its SHA-256 file
    python build/build.py --smoke    also run the packaged app with --smoke-test

The version is read from src/desktop_organizer/__init__.py, so the .exe metadata, the app
and the release always carry the same number.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INIT_FILE = ROOT / "src" / "desktop_organizer" / "__init__.py"
SPEC_FILE = ROOT / "build" / "desktop_organizer.spec"
VERSION_FILE = ROOT / "build" / "version_info.txt"
DIST = ROOT / "dist"
COPYRIGHT = "Copyright (c) 2026. All rights reserved."
COMPANY = "Desktop Organizer"


def read_version() -> str:
    match = re.search(r'__version__\s*=\s*"([^"]+)"', INIT_FILE.read_text(encoding="utf-8"))
    if not match:
        raise SystemExit("__version__ not found in " + str(INIT_FILE))
    version = match.group(1)
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        raise SystemExit(f"Version must be semantic MAJOR.MINOR.PATCH, got {version!r}")
    return version


def write_version_info(version: str) -> None:
    """Windows version resource: name, version, company and copyright shown in file properties."""
    major, minor, patch = (int(part) for part in version.split("."))
    tuple_text = f"({major}, {minor}, {patch}, 0)"
    text = f"""# UTF-8
# Generated by build/build.py. Do not edit by hand.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={tuple_text},
    prodvers={tuple_text},
    mask=0x3F,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable(
        '040704B0',
        [StringStruct('CompanyName', '{COMPANY}'),
         StringStruct('FileDescription', 'Desktop Organizer'),
         StringStruct('FileVersion', '{version}'),
         StringStruct('InternalName', 'DesktopOrganizer'),
         StringStruct('LegalCopyright', '{COPYRIGHT}'),
         StringStruct('OriginalFilename', 'DesktopOrganizer.exe'),
         StringStruct('ProductName', 'Desktop Organizer'),
         StringStruct('ProductVersion', '{version}')])
    ]),
    VarFileInfo([VarStruct('Translation', [1031, 1200])])
  ]
)
"""
    VERSION_FILE.write_text(text, encoding="utf-8")


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def build() -> Path:
    version = read_version()
    if sys.platform.startswith("win"):
        write_version_info(version)
    command = [
        sys.executable,
        "-m",
        "PyInstaller",
        "--noconfirm",
        "--clean",
        "--workpath",
        str(ROOT / "build" / "pyinstaller"),
        "--distpath",
        str(DIST),
        str(SPEC_FILE),
    ]
    subprocess.run(command, cwd=ROOT, check=True)
    exe_name = "DesktopOrganizer.exe" if sys.platform.startswith("win") else "DesktopOrganizer"
    artifact = DIST / exe_name
    if not artifact.exists():
        raise SystemExit(f"Build finished but {artifact} is missing")
    checksum = sha256(artifact)
    (DIST / f"{exe_name}.sha256").write_text(f"{checksum}  {exe_name}\n", encoding="utf-8")
    print(f"Built {artifact} (version {version})")
    print(f"SHA-256 {checksum}")
    return artifact


def smoke(artifact: Path) -> None:
    result = subprocess.run([str(artifact), "--smoke-test"], check=False, timeout=180)
    if result.returncode != 0:
        raise SystemExit(f"Smoke test failed with exit code {result.returncode}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--smoke", action="store_true", help="run the packaged app with --smoke-test")
    args = parser.parse_args()
    artifact = build()
    if args.smoke:
        smoke(artifact)


if __name__ == "__main__":
    main()
